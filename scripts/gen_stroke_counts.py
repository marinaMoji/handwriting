#!/usr/bin/env python3
"""Generate src/StrokeCountTable.inc: expected stroke counts for the characters Zinnia can output.

usage: gen_stroke_counts.py [--unihan data/Unihan_IRGSources.txt] [--models models]

Needs: bash scripts/fetch_unihan.sh, the models (scripts/fetch_models.sh) and the dump_charset
target built in ./build. Counts come from the Unihan kTotalStrokes field (Unicode License V3).
"""
import os, re, subprocess, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
arg = lambda name, default: sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default
unihan = arg("--unihan", os.path.join(root, "data", "Unihan_IRGSources.txt"))
models = arg("--models", os.path.join(root, "models"))
dump = os.path.join(root, "build", "dump_charset")

header = open(unihan, encoding="utf-8").read(2000)
version = (re.search(r"# Unicode Version ([\d.]+)", header) or [None, "?"])[1]
counts = {}
for line in open(unihan, encoding="utf-8"):
    m = re.match(r"U\+([0-9A-F]+)\tkTotalStrokes\t(\d+)", line)
    if m:
        counts[int(m.group(1), 16)] = int(m.group(2))

out = subprocess.run([dump, os.path.join(models, "handwriting-ja.model"),
                      os.path.join(models, "handwriting-zh_TW.model")],
                     capture_output=True, text=True, check=True).stdout
charset = sorted({ord(c) for c in out.split() if len(c) == 1})
rows = [(cp, counts[cp]) for cp in charset if cp in counts]
missing = [cp for cp in charset if cp not in counts]

with open(os.path.join(root, "src", "StrokeCountTable.inc"), "w", encoding="utf-8") as f:
    f.write(f"""// Generated by scripts/gen_stroke_counts.py. Do not edit.
//
// Expected stroke counts for the characters the Tegaki ja / zh_TW Zinnia models can output.
// Derived from the Unihan kTotalStrokes field (Unicode {version}).
// Copyright (c) 1991-2026 Unicode, Inc. Distributed under the Unicode License v3,
// https://www.unicode.org/license.txt. Characters without a count (kana, ASCII) are omitted.
//
// {len(rows)} entries, sorted by code point.
""")
    f.write("static const unsigned int kStrokeCountCodePoints[] = {\n")
    def block(items):
        return ",\n".join(",".join(items[i:i + 12]) for i in range(0, len(items), 12))
    f.write(block([f"0x{cp:X}" for cp, _ in rows]))
    f.write("};\nstatic const unsigned char kStrokeCounts[] = {\n")
    f.write(block([str(n) for _, n in rows]))
    f.write("};\n")
print(f"{len(rows)} entries written; {len(missing)} model characters without a count: "
      + "".join(chr(c) for c in missing[:40]))
